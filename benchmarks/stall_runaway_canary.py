"""Production-scale stall-runaway regression canary (issue #456).

Runs a non-monkeypatched 2-site implicit-AD Heisenberg optimization and
asserts that the stall counter stays bounded by ``gs_stall_recovery_retries``
and wall-clock stays under a budget.  Complements the structural unit tests
in ``tests/test_ipeps_stall_recovery_cap.py`` by exercising the cap+rollback
on a real CTM gradient (#454 follow-up).

Usage::

    uv run python benchmarks/stall_runaway_canary.py            # default canary
    uv run python benchmarks/stall_runaway_canary.py --smoke    # tiny config (~minutes)
    uv run python benchmarks/stall_runaway_canary.py --d 3      # D=3 χ=8 variant

Exits non-zero when:

* ``stall #N`` lines in the optimizer's verbose stdout exceed the cap
  (``gs_stall_recovery_retries``).  Under the #454 fix the cap is a hard
  bound; exceeding it is the regression this canary watches for.
* Wall-clock exceeds ``--max-wall-time`` (default 90 minutes).

Run on demand when a CI-class GPU is allocated.  Not a pytest target — the
30-60 min wall-clock budget is too heavy for the test bucket.
"""

from __future__ import annotations

import argparse
import io
import re
import sys
import time
from contextlib import redirect_stdout

import jax.numpy as jnp

from tenax import CTMConfig, iPEPSConfig, optimize_gs_ad

_STALL_RE = re.compile(r"\[iPEPS-AD\][^\n]*stall #(\d+)")


def _heisenberg_gate(dtype=jnp.complex128):
    Sz = jnp.array([[0.5, 0.0], [0.0, -0.5]], dtype=dtype)
    Sp = jnp.array([[0.0, 1.0], [0.0, 0.0]], dtype=dtype)
    Sm = jnp.array([[0.0, 0.0], [1.0, 0.0]], dtype=dtype)
    H = jnp.kron(Sz, Sz) + 0.5 * (jnp.kron(Sp, Sm) + jnp.kron(Sm, Sp))
    return H.reshape(2, 2, 2, 2)


def _max_stall_seen(stdout_text: str) -> int:
    """Return ``max N`` from any ``[iPEPS-AD] stall #N`` lines, or 0."""
    counts = [int(m.group(1)) for m in _STALL_RE.finditer(stdout_text)]
    return max(counts) if counts else 0


def run_canary(
    *,
    D: int = 2,
    chi: int = 8,
    gs_num_steps: int = 20,
    gs_stall_recovery_retries: int = 5,
) -> dict:
    """Run one stall-runaway canary trajectory and return a result dict.

    Initial site tensors are generated by the optimizer's internal random
    init (``jax.random.PRNGKey(0)``), which is deterministic across runs.
    """
    gate = _heisenberg_gate()
    config = iPEPSConfig(
        max_bond_dim=D,
        unit_cell="2site",
        ctm=CTMConfig(chi=chi),
        gs_implicit_ad=True,
        gs_optimizer="lbfgs",
        gs_num_steps=gs_num_steps,
        gs_stall_recovery="reset",
        gs_stall_recovery_retries=gs_stall_recovery_retries,
        gs_conv_criterion="grad_norm",
        gs_verbose=True,
    )

    t0 = time.perf_counter()
    buf = io.StringIO()
    # ``optimize_gs_ad`` emits ``[iPEPS-AD] stall #N, ...`` lines via
    # ``print(..., flush=True)`` when ``gs_verbose=True``; capture them so
    # we can parse the realized max stall count without depending on the
    # logger configuration.
    with redirect_stdout(buf):
        result = optimize_gs_ad(gate, None, config)
    stdout_text = buf.getvalue()
    wall = time.perf_counter() - t0

    max_stall = _max_stall_seen(stdout_text)
    cap_hit = max_stall > gs_stall_recovery_retries

    # 2-site optimize_gs_ad returns ((A, B), (env_A, env_B), E_gs); pick last.
    final_energy = float(result[-1])

    return {
        "D": D,
        "chi": chi,
        "gs_num_steps": gs_num_steps,
        "cap": gs_stall_recovery_retries,
        "max_stall_seen": max_stall,
        "cap_exceeded": cap_hit,
        "final_energy": final_energy,
        "wall_seconds": wall,
        "stdout": stdout_text,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--d", type=int, default=2, help="Bond dim (default 2)")
    parser.add_argument("--chi", type=int, default=8, help="CTM chi (default 8)")
    parser.add_argument(
        "--steps", type=int, default=20, help="gs_num_steps (default 20)"
    )
    parser.add_argument(
        "--cap",
        type=int,
        default=5,
        help="gs_stall_recovery_retries (default 5; cap-exceeded triggers exit 1)",
    )
    parser.add_argument(
        "--max-wall-time",
        type=float,
        default=90 * 60,
        help="Hard wall-clock budget in seconds (default 90 min)",
    )
    parser.add_argument(
        "--smoke",
        action="store_true",
        help="Tiny config (D=2, chi=4, 5 steps) for dev-machine smoke tests",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="Suppress captured optimizer stdout in the report",
    )
    args = parser.parse_args(argv)

    if args.smoke:
        args.chi = 4
        args.steps = 5

    print(
        f"[canary] D={args.d} chi={args.chi} steps={args.steps} cap={args.cap}",
        flush=True,
    )
    out = run_canary(
        D=args.d,
        chi=args.chi,
        gs_num_steps=args.steps,
        gs_stall_recovery_retries=args.cap,
    )

    if not args.quiet:
        print("---- captured optimizer stdout ----", flush=True)
        print(out["stdout"], flush=True)
        print("---- end captured stdout ----", flush=True)

    print(
        f"[canary] final_energy={out['final_energy']:.10f} "
        f"max_stall_seen={out['max_stall_seen']} "
        f"cap_exceeded={out['cap_exceeded']} "
        f"wall_seconds={out['wall_seconds']:.1f}",
        flush=True,
    )

    rc = 0
    if out["cap_exceeded"]:
        print(
            f"[canary] FAIL: stall counter reached {out['max_stall_seen']} > "
            f"cap={args.cap} — #454 regression",
            flush=True,
        )
        rc = 1
    if out["wall_seconds"] > args.max_wall_time:
        print(
            f"[canary] FAIL: wall_seconds={out['wall_seconds']:.1f} exceeds "
            f"--max-wall-time={args.max_wall_time:.1f}",
            flush=True,
        )
        rc = 1
    return rc


if __name__ == "__main__":
    sys.exit(main())
